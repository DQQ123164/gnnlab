#!/usr/bin/env python3
"""Build stable training artifacts for the GNNLab skeleton datasets."""

from __future__ import annotations

import argparse
import logging
from pathlib import Path
from typing import Any, Sequence

if __package__:
    from .preprocessing import (
        DatasetName,
        LOGGER,
        clean_processed_datasets,
        env_path,
        load_env_file,
        optional_env_path,
        preprocess_dsg,
        preprocess_ssg,
    )
else:
    from preprocessing import (
        DatasetName,
        LOGGER,
        clean_processed_datasets,
        env_path,
        load_env_file,
        optional_env_path,
        preprocess_dsg,
        preprocess_ssg,
    )


def parse_args() -> argparse.Namespace:
    project_root = Path(__file__).resolve().parents[1]
    load_env_file(project_root / ".env")
    default_root = env_path("GNNLAB_ROOT", project_root)

    parser = argparse.ArgumentParser(
        description="Preprocess dsg and ssg into reusable gnnlab artifacts.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=default_root,
        help="Repository root. Can also be set with GNNLAB_ROOT.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=optional_env_path("GNNLAB_PROCESSED_DIR"),
        help=(
            "Processed output directory. Defaults to GNNLAB_PROCESSED_DIR or "
            "ROOT/processed."
        ),
    )
    parser.add_argument(
        "--dsg-source",
        type=Path,
        default=optional_env_path("GNNLAB_DSG_DIR"),
        help=(
            "Directory containing DSG data. Defaults to GNNLAB_DSG_DIR or "
            "ROOT/dsg; ROOT/dsg/nturgb+d_skeletons is also detected."
        ),
    )
    parser.add_argument(
        "--ssg-source",
        type=Path,
        default=optional_env_path("GNNLAB_SSG_DIR"),
        help="Directory containing SSG data. Defaults to GNNLAB_SSG_DIR or ROOT/ssg.",
    )
    parser.add_argument(
        "--datasets",
        nargs="+",
        choices=("dsg", "ssg", "all"),
        default=["all"],
        help="Dataset groups to process.",
    )
    output_mode = parser.add_mutually_exclusive_group()
    output_mode.add_argument(
        "--overwrite",
        action="store_true",
        help="Replace files previously generated by this script.",
    )
    output_mode.add_argument(
        "--clean",
        action="store_true",
        help="Delete generated output for the selected datasets and exit.",
    )
    parser.add_argument(
        "--ssg-min-confidence",
        type=float,
        default=0.0,
        help="Minimum OpenPose confidence for a joint to affect normalization.",
    )
    parser.add_argument(
        "--log-level",
        default="INFO",
        choices=("DEBUG", "INFO", "WARNING", "ERROR"),
        help="Logging verbosity.",
    )
    parser.add_argument(
        "--no-progress",
        action="store_true",
        help="Disable progress bars and periodic progress messages.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    logging.basicConfig(
        level=getattr(logging, args.log_level),
        format="%(levelname)s %(message)s",
    )

    root = args.root.resolve()
    output_dir = (args.output_dir or root / "processed").resolve()
    selected = expand_datasets(args.datasets)

    if not root.exists():
        raise FileNotFoundError(f"Repository root does not exist: {root}")

    if args.clean:
        clean_processed_datasets(output_dir, selected)
        return

    output_dir.mkdir(parents=True, exist_ok=True)
    metadata_by_dataset: dict[DatasetName, dict[str, Any]] = {}

    if "dsg" in selected:
        metadata_by_dataset["dsg"] = preprocess_dsg(
            source_dir=(args.dsg_source or root / "dsg").resolve(),
            output_dir=output_dir / "dsg",
            overwrite=args.overwrite,
            show_progress=not args.no_progress,
        )

    if "ssg" in selected:
        metadata_by_dataset["ssg"] = preprocess_ssg(
            source_dir=(args.ssg_source or root / "ssg").resolve(),
            output_dir=output_dir / "ssg",
            overwrite=args.overwrite,
            min_confidence=args.ssg_min_confidence,
            show_progress=not args.no_progress,
        )

    log_output_summaries(metadata_by_dataset)
    LOGGER.info("Output directory: %s", output_dir)
    LOGGER.info("[DONE] Preprocessing completed")


def log_output_summaries(
    metadata_by_dataset: dict[DatasetName, dict[str, Any]],
) -> None:
    for dataset in sorted(metadata_by_dataset):
        for summary in metadata_by_dataset[dataset]["splits"]:
            protocol = summary.get("protocol")
            sample_count = summary["sample_count"]
            data_file = summary["data_file"]
            if not data_file.endswith("_data.npy"):
                raise ValueError(f"Unexpected generated data filename: {data_file}")
            label_file = f"{data_file.removesuffix('_data.npy')}_label.npy"
            scope = (
                f"{dataset} {protocol}/{summary['split']}"
                if protocol
                else f"{dataset} {summary['split']}"
            )
            LOGGER.info(
                "%s: samples=%d | %s %s %s | %s int64 (%d,)",
                scope,
                sample_count,
                data_file,
                summary["dtype"],
                tuple(summary["data_shape"]),
                label_file,
                sample_count,
            )


def expand_datasets(values: Sequence[str]) -> set[DatasetName]:
    if "all" in values:
        return {"dsg", "ssg"}
    return {value for value in values if value in {"dsg", "ssg"}}  # type: ignore[return-value]


if __name__ == "__main__":
    main()
