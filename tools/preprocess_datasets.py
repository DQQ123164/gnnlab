def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Preprocess dsg and ssg into reusable gnnlab artifacts.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="Repository root containing dsg/ and ssg/.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Processed output directory. Defaults to ROOT/processed.",
    )
    parser.add_argument(
        "--datasets",
        nargs="+",
        choices=("dsg", "ssg", "all"),
        default=["all"],
        help="Dataset groups to process.",
    )
    output_mode = parser.add_mutually_exclusive_group()
    output_mode.add_argument(
        "--overwrite",
        action="store_true",
        help="Replace files previously generated by this script.",
    )
    output_mode.add_argument(
        "--clean",
        action="store_true",
        help="Delete generated output for the selected datasets and exit.",
    )
    parser.add_argument(
        "--ssg-min-confidence",
        type=float,
        default=0.0,
        help="Minimum OpenPose confidence for a joint to affect normalization.",
    )
    parser.add_argument(
        "--log-level",
        default="INFO",
        choices=("DEBUG", "INFO", "WARNING", "ERROR"),
        help="Logging verbosity.",
    )
    parser.add_argument(
        "--no-progress",
        action="store_true",
        help="Disable progress bars and periodic progress messages.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    logging.basicConfig(
        level=getattr(logging, args.log_level),
        format="%(levelname)s %(message)s",
    )

    root = args.root.resolve()
    output_dir = (args.output_dir or root / "processed").resolve()
    selected = expand_datasets(args.datasets)

    if not root.exists():
        raise FileNotFoundError(f"Repository root does not exist: {root}")

    if args.clean:
        clean_processed_datasets(output_dir, selected)
        return

    output_dir.mkdir(parents=True, exist_ok=True)

    if "dsg" in selected:
        preprocess_dsg(
            source_dir=root / "dsg",
            output_dir=output_dir / "dsg",
            overwrite=args.overwrite,
            show_progress=not args.no_progress,
        )

    if "ssg" in selected:
        preprocess_ssg(
            source_dir=root / "ssg",
            output_dir=output_dir / "ssg",
            overwrite=args.overwrite,
            min_confidence=args.ssg_min_confidence,
        )

    LOGGER.info("Done. Processed artifacts are under %s", output_dir)


def expand_datasets(values: Sequence[str]) -> set[DatasetName]:
    if "all" in values:
        return {"dsg", "ssg"}
    return {value for value in values if value in {"dsg", "ssg"}}  # type: ignore[return-value]


def clean_processed_datasets(
    output_dir: Path,
    selected: set[DatasetName],
) -> None:
    if output_dir.exists() and not output_dir.is_dir():
        raise NotADirectoryError(f"Processed output is not a directory: {output_dir}")

    removed = 0
    for dataset in sorted(selected):
        target = output_dir / dataset
        if target.is_symlink() or target.is_file():
            target.unlink()
        elif target.is_dir():
            shutil.rmtree(target)
        else:
            LOGGER.info("Nothing to clean for %s: %s", dataset, target)
            continue
        removed += 1
        LOGGER.info("Removed generated %s data: %s", dataset, target)

    if removed == 0:
        LOGGER.info("No generated dataset output was found under %s", output_dir)


def preprocess_dsg(
    source_dir: Path,
    output_dir: Path,
    overwrite: bool,
    show_progress: bool,
) -> dict[str, Any]:
    require_dir(source_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    summaries: list[DsgSplitSummary] = []
    protocols = [path for path in sorted(source_dir.iterdir()) if path.is_dir()]
    if not protocols:
        raise FileNotFoundError(f"No dsg protocols found under {source_dir}")

    for protocol_dir in protocols:
        protocol = protocol_dir.name
        protocol_out = output_dir / protocol
        protocol_out.mkdir(parents=True, exist_ok=True)

        for split in ("train", "test"):
            split_name: SplitName = split  # type: ignore[assignment]
            split_dir = protocol_dir / split
            require_dir(split_dir)
            skeleton_paths = sorted(split_dir.glob("*.skeleton"))
            if not skeleton_paths:
                raise FileNotFoundError(f"No .skeleton files found under {split_dir}")

            data_dst = protocol_out / f"{split}_data.npy"
            label_dst = protocol_out / f"{split}_label.pkl"
            label_npy_dst = protocol_out / f"{split}_label.npy"
            samples_dst = protocol_out / f"{split}_samples.txt"
            manifest_dst = protocol_out / f"{split}_manifest.jsonl"
            destinations = (
                data_dst,
                label_dst,
                label_npy_dst,
                samples_dst,
                manifest_dst,
            )
            for destination in destinations:
                prepare_destination(destination, overwrite)

            labels_and_actions = [parse_dsg_label(path) for path in skeleton_paths]
            labels = [item[0] for item in labels_and_actions]
            action_ids = [item[1] for item in labels_and_actions]
            sample_names = [path.name for path in skeleton_paths]
            records = write_dsg_array(
                skeleton_paths=skeleton_paths,
                action_ids=action_ids,
                labels=labels,
                protocol=protocol,
                split=split_name,
                source_dir=source_dir,
                destination=data_dst,
                overwrite=overwrite,
                show_progress=show_progress,
            )
            atomic_save_npy(
                label_npy_dst,
                np.asarray(labels, dtype=np.int64),
                overwrite=overwrite,
            )
            write_text(
                samples_dst,
                "\n".join(sample_names) + "\n",
                overwrite=overwrite,
            )
            write_pickle(
                label_dst,
                (sample_names, labels),
                overwrite=overwrite,
            )
            write_jsonl(
                manifest_dst,
                [asdict(record) for record in records],
                overwrite=overwrite,
            )

            shape = (
                len(skeleton_paths),
                3,
                DSG_MAX_FRAMES,
                DSG_NUM_JOINTS,
                DSG_MAX_BODIES,
            )
            summaries.append(
                DsgSplitSummary(
                    protocol=protocol,
                    split=split_name,
                    data_file=relative_to(data_dst, output_dir),
                    label_file=relative_to(label_dst, output_dir),
                    data_shape=shape,
                    dtype="float32",
                    sample_count=len(labels),
                    label_counts=count_labels(labels),
                    source_bytes=sum(path.stat().st_size for path in skeleton_paths),
                    manifest_file=relative_to(manifest_dst, output_dir),
                    warnings=count_warning_types(records),
                )
            )

    metadata = {
        "consumer": "st-gcn",
        "source_format": "NTU RGB+D .skeleton text files",
        "format": {
            "data": "float32 numpy array shaped (N, C, T, V, M)",
            "channels": ["x", "y", "z"],
            "max_frames": DSG_MAX_FRAMES,
            "num_joints": DSG_NUM_JOINTS,
            "max_bodies": DSG_MAX_BODIES,
            "padding": "missing frames and bodies are zero-filled",
            "overflow": "frames after max_frames and bodies after max_bodies are discarded",
            "label_pkl": "pickle tuple (sample_names, labels)",
            "label_npy": "int64 labels aligned with data rows",
        },
        "class_map": DSG_CLASS_MAP,
        "splits": [asdict(summary) for summary in summaries],
    }
    write_json(output_dir / "metadata.json", metadata, overwrite=overwrite)
    LOGGER.info("dsg: converted %d protocol splits", len(summaries))
    return metadata


def parse_dsg_label(path: Path) -> tuple[int, str]:
    match = DSG_ACTION_PATTERN.search(path.name)
    if match is None:
        raise ValueError(f"Cannot parse NTU action ID from filename: {path.name}")
    action_id = match.group(1)
    if action_id not in DSG_ACTION_LABELS:
        expected = ", ".join(DSG_ACTION_LABELS)
        raise ValueError(
            f"Unsupported action {action_id} in {path.name}; expected one of {expected}"
        )
    return DSG_ACTION_LABELS[action_id], action_id


def write_dsg_array(
    skeleton_paths: Sequence[Path],
    action_ids: Sequence[str],
    labels: Sequence[int],
    protocol: str,
    split: SplitName,
    source_dir: Path,
    destination: Path,
    overwrite: bool,
    show_progress: bool,
) -> list[DsgSampleRecord]:
    prepare_destination(destination, overwrite)
    tmp_path = destination.with_name(f".{destination.name}.tmp")
    if tmp_path.exists() or tmp_path.is_symlink():
        tmp_path.unlink()

    shape = (
        len(skeleton_paths),
        3,
        DSG_MAX_FRAMES,
        DSG_NUM_JOINTS,
        DSG_MAX_BODIES,
    )
    records: list[DsgSampleRecord] = []
    progress = ProgressBar(f"dsg {protocol}/{split}", len(skeleton_paths), show_progress)
    data: np.memmap | None = None
    try:
        data = np.lib.format.open_memmap(
            tmp_path,
            mode="w+",
            dtype=np.float32,
            shape=shape,
        )
        for index, (path, action_id, label) in enumerate(
            zip(skeleton_paths, action_ids, labels, strict=True)
        ):
            sample, stats = parse_ntu_skeleton(path)
            if sample.shape[1] > 0:
                data[index, :, : sample.shape[1], :, :] = sample

            warnings: list[str] = []
            if stats["frame_count"] > DSG_MAX_FRAMES:
                warnings.append("frames_truncated")
            if stats["dropped_body_instances"] > 0:
                warnings.append("bodies_dropped")
            if stats["empty_frame_count"] > 0:
                warnings.append("empty_frames")

            records.append(
                DsgSampleRecord(
                    sample_name=path.name,
                    protocol=protocol,
                    split=split,
                    action_id=action_id,
                    label=label,
                    source_path=relative_to(path, source_dir),
                    frame_count=stats["frame_count"],
                    stored_frame_count=min(stats["frame_count"], DSG_MAX_FRAMES),
                    max_body_count=stats["max_body_count"],
                    empty_frame_count=stats["empty_frame_count"],
                    dropped_body_instances=stats["dropped_body_instances"],
                    warnings=warnings,
                )
            )
            progress.update(index + 1)

        data.flush()
        del data
        data = None
        tmp_path.replace(destination)
    except BaseException:
        if data is not None:
            del data
        if tmp_path.exists() or tmp_path.is_symlink():
            tmp_path.unlink()
        raise
    return records


def parse_ntu_skeleton(path: Path) -> tuple[np.ndarray, dict[str, int]]:
    line_number = [0]
    with path.open("r", encoding="utf-8") as file:
        frame_count = parse_integer_line(
            read_required_line(file, path, line_number, "frame count"),
            path,
            line_number[0],
            "frame count",
        )
        if frame_count < 0:
            raise ValueError(f"{path}:{line_number[0]} frame count cannot be negative")

        stored_frames = min(frame_count, DSG_MAX_FRAMES)
        sample = np.zeros(
            (3, stored_frames, DSG_NUM_JOINTS, DSG_MAX_BODIES),
            dtype=np.float32,
        )
        max_body_count = 0
        empty_frame_count = 0
        dropped_body_instances = 0

        for frame_index in range(frame_count):
            body_count = parse_integer_line(
                read_required_line(file, path, line_number, "body count"),
                path,
                line_number[0],
                "body count",
            )
            if body_count < 0:
                raise ValueError(f"{path}:{line_number[0]} body count cannot be negative")
            max_body_count = max(max_body_count, body_count)
            if body_count == 0:
                empty_frame_count += 1
            dropped_body_instances += max(0, body_count - DSG_MAX_BODIES)

            for body_index in range(body_count):
                body_info = read_required_line(file, path, line_number, "body info").split()
                if len(body_info) < 10:
                    raise ValueError(
                        f"{path}:{line_number[0]} body info must contain at least 10 values"
                    )
                joint_count = parse_integer_line(
                    read_required_line(file, path, line_number, "joint count"),
                    path,
                    line_number[0],
                    "joint count",
                )
                if joint_count != DSG_NUM_JOINTS:
                    raise ValueError(
                        f"{path}:{line_number[0]} expected {DSG_NUM_JOINTS} joints, "
                        f"got {joint_count}"
                    )

                keep_body = (
                    frame_index < stored_frames and body_index < DSG_MAX_BODIES
                )
                for joint_index in range(joint_count):
                    values = read_required_line(
                        file,
                        path,
                        line_number,
                        "joint info",
                    ).split()
                    if len(values) < 12:
                        raise ValueError(
                            f"{path}:{line_number[0]} joint info must contain at least 12 values"
                        )
                    if keep_body:
                        try:
                            sample[:, frame_index, joint_index, body_index] = (
                                float(values[0]),
                                float(values[1]),
                                float(values[2]),
                            )
                        except ValueError as exc:
                            raise ValueError(
                                f"{path}:{line_number[0]} invalid x/y/z joint coordinates"
                            ) from exc

        if file.read().strip():
            raise ValueError(f"{path}: unexpected data after {frame_count} frames")

    return sample, {
        "frame_count": frame_count,
        "max_body_count": max_body_count,
        "empty_frame_count": empty_frame_count,
        "dropped_body_instances": dropped_body_instances,
    }


def read_required_line(
    file: Any,
    path: Path,
    line_number: list[int],
    field: str,
) -> str:
    line = file.readline()
    line_number[0] += 1
    if line == "":
        raise ValueError(f"{path}:{line_number[0]} unexpected EOF while reading {field}")
    return line.strip()


def parse_integer_line(value: str, path: Path, line_number: int, field: str) -> int:
    try:
        return int(value)
    except ValueError as exc:
        raise ValueError(f"{path}:{line_number} invalid {field}: {value!r}") from exc


class ProgressBar:
    def __init__(self, label: str, total: int, enabled: bool) -> None:
        self.label = label
        self.total = total
        self.enabled = enabled
        self.started_at = time.monotonic()
        self.last_rendered_at = 0.0
        self.log_interval = max(1, total // 20)

    def update(self, completed: int) -> None:
        if not self.enabled:
            return
        now = time.monotonic()
        elapsed = max(now - self.started_at, 1e-9)
        rate = completed / elapsed
        remaining = max(self.total - completed, 0)
        eta = remaining / rate if rate > 0 else 0.0
        percent = completed / self.total if self.total else 1.0

        if sys.stderr.isatty():
            if completed < self.total and now - self.last_rendered_at < 0.1:
                return
            width = 28
            filled = min(width, int(width * percent))
            bar = "#" * filled + "-" * (width - filled)
            message = (
                f"\r{self.label:<20} [{bar}] {completed:>{len(str(self.total))}}/"
                f"{self.total} {percent:6.2%} {rate:6.1f} samples/s "
                f"ETA {format_duration(eta)}"
            )
            print(
                message,
                file=sys.stderr,
                end="\n" if completed == self.total else "",
                flush=True,
            )
            self.last_rendered_at = now
        elif completed == self.total or completed % self.log_interval == 0:
            LOGGER.info(
                "%s progress: %d/%d (%.1f%%), %.1f samples/s, ETA %s",
                self.label,
                completed,
                self.total,
                percent * 100,
                rate,
                format_duration(eta),
            )


def format_duration(seconds: float) -> str:
    seconds = max(0, int(round(seconds)))
    minutes, seconds = divmod(seconds, 60)
    hours, minutes = divmod(minutes, 60)
    if hours:
        return f"{hours:d}:{minutes:02d}:{seconds:02d}"
    return f"{minutes:02d}:{seconds:02d}"
def preprocess_ssg(
    source_dir: Path,
    output_dir: Path,
    overwrite: bool,
    min_confidence: float,
) -> dict[str, Any]:
    require_dir(source_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    summaries: list[SsgSplitSummary] = []
    for split in ("train", "test"):
        split_name: SplitName = split  # type: ignore[assignment]
        samples, skipped_records = collect_ssg_samples(
            source_dir,
            split_name,
            min_confidence,
        )
        if not samples:
            raise FileNotFoundError(
                f"No usable ssg {split} JSON files found under {source_dir}"
            )

        norm_data = np.stack([sample[1] for sample in samples]).astype(np.float32)
        records = [sample[2] for sample in samples]
        labels = np.asarray([record.label for record in records], dtype=np.int64)

        data_dst = output_dir / f"{split}_data.npy"
        label_dst = output_dir / f"{split}_label.npy"
        atomic_save_npy(data_dst, norm_data, overwrite=overwrite)
        atomic_save_npy(label_dst, labels, overwrite=overwrite)

        summaries.append(
            SsgSplitSummary(
                split=split_name,
                data_file=relative_to(data_dst, output_dir),
                label_file=relative_to(label_dst, output_dir),
                source_count=len(records) + len(skipped_records),
                sample_count=len(records),
                skipped_count=len(skipped_records),
                data_shape=tuple(norm_data.shape),
                dtype=str(norm_data.dtype),
                label_counts=count_labels(labels.tolist()),
                warnings=count_warning_types(records + skipped_records),
            )
        )

    metadata = {
        "consumer": "gcnlab",
        "format": {
            "data": "float32 numpy array shaped (N, V, C)",
            "channels": ["x_normalized", "y_normalized", "confidence"],
            "label_npy": "int64 labels aligned with data rows",
            "normalization": {
                "center": "mean of valid MidHip/RHip/LHip; fallback to upper torso or all valid joints",
                "rotation": "align hip-center-to-Neck axis vertically; fallback to shoulder axis or image axes",
                "scale": "median valid torso-edge length; fallback to bbox max side or 1.0",
                "invalid_joint": "x/y/confidence are set to 0",
                "invalid_sample": "samples without any valid BODY_25 joint are skipped",
                "min_confidence": min_confidence,
            },
            "person_selection": "highest sum of BODY_25 joint confidence",
        },
        "class_map": SSG_CLASS_MAP,
        "body25": {
            "joint_names": BODY25_JOINT_NAMES,
            "edges": BODY25_EDGES,
        },
        "splits": [asdict(summary) for summary in summaries],
    }
    write_json(output_dir / "metadata.json", metadata, overwrite=overwrite)
    if overwrite:
        remove_obsolete_ssg_outputs(output_dir)
    LOGGER.info(
        "ssg: converted %d compact splits (%d usable samples, %d skipped)",
        len(summaries),
        sum(summary.sample_count for summary in summaries),
        sum(summary.skipped_count for summary in summaries),
    )
    return metadata


def remove_obsolete_ssg_outputs(output_dir: Path) -> None:
    obsolete_names = (
        "train_data_raw.npy",
        "test_data_raw.npy",
        "train_label.pkl",
        "test_label.pkl",
        "train_samples.txt",
        "test_samples.txt",
        "train_manifest.jsonl",
        "test_manifest.jsonl",
        "body25_adjacency.npy",
        "body25_edge_index.npy",
        "body25_graph.json",
    )
    for name in obsolete_names:
        path = output_dir / name
        if path.exists() or path.is_symlink():
            path.unlink()


def collect_ssg_samples(
    source_dir: Path,
    split: SplitName,
    min_confidence: float,
) -> tuple[
    list[tuple[np.ndarray, np.ndarray, SsgSampleRecord]],
    list[SsgSampleRecord],
]:
    samples: list[tuple[np.ndarray, np.ndarray, SsgSampleRecord]] = []
    skipped_records: list[SsgSampleRecord] = []
    for class_name, label in sorted(SSG_CLASS_MAP.items(), key=lambda item: item[1]):
        split_dir = source_dir / class_name / split
        require_dir(split_dir)
        for json_path in sorted(split_dir.glob("*.json")):
            raw, normalized, record = parse_ssg_json(
                json_path=json_path,
                source_dir=source_dir,
                split=split,
                class_name=class_name,
                label=label,
                min_confidence=min_confidence,
            )
            if record.valid_joint_count == 0:
                skipped_records.append(record)
                continue
            samples.append((raw, normalized, record))
    return samples, skipped_records


def parse_ssg_json(
    json_path: Path,
    source_dir: Path,
    split: SplitName,
    class_name: str,
    label: int,
    min_confidence: float,
) -> tuple[np.ndarray, np.ndarray, SsgSampleRecord]:
    with json_path.open("r", encoding="utf-8") as file:
        payload = json.load(file)

    people = payload.get("people") or []
    warnings: list[str] = []
    selected_index: int | None = None
    selected_confidence_sum = 0.0
    raw = np.zeros((25, 3), dtype=np.float32)

    if not people:
        warnings.append("no_person")
    else:
        selected_index, selected = select_person(people)
        keypoints = selected.get("pose_keypoints_2d") or []
        selected_confidence_sum = confidence_sum(keypoints)
        if len(keypoints) != 75:
            warnings.append("invalid_keypoint_length")
        else:
            raw = np.asarray(keypoints, dtype=np.float32).reshape(25, 3)
        if len(people) > 1:
            warnings.append("multi_person")

    normalized, center, scale, valid_count, norm_warnings = normalize_body25(
        raw,
        min_confidence=min_confidence,
    )
    warnings.extend(norm_warnings)

    record = SsgSampleRecord(
        sample_name=json_path.stem,
        split=split,
        class_name=class_name,
        label=label,
        source_path=relative_to(json_path, source_dir),
        people_count=len(people),
        selected_person_index=selected_index,
        selected_confidence_sum=float(selected_confidence_sum),
        valid_joint_count=valid_count,
        center=[float(center[0]), float(center[1])],
        scale=float(scale),
        warnings=warnings,
    )
    return raw, normalized, record


def select_person(people: Sequence[dict[str, Any]]) -> tuple[int, dict[str, Any]]:
    scores = [
        confidence_sum(person.get("pose_keypoints_2d") or [])
        for person in people
    ]
    selected_index = int(np.argmax(np.asarray(scores, dtype=np.float32)))
    return selected_index, people[selected_index]


def confidence_sum(keypoints: Sequence[float]) -> float:
    if len(keypoints) < 3:
        return 0.0
    return float(sum(float(value) for value in keypoints[2::3]))


def normalize_body25(
    raw: np.ndarray,
    min_confidence: float,
) -> tuple[np.ndarray, np.ndarray, float, int, list[str]]:
    warnings: list[str] = []
    normalized = np.zeros_like(raw, dtype=np.float32)

    valid = valid_joint_mask(raw, min_confidence)
    valid_count = int(valid.sum())
    if valid_count == 0:
        warnings.append("no_valid_joints")
        return normalized, np.asarray([0.0, 0.0], dtype=np.float32), 1.0, 0, warnings

    center, center_source = estimate_center(raw, valid)
    aligned_xy, rotation_source = align_body25(raw, valid, center, center_source)
    scale, scale_source = estimate_scale(raw, valid)
    if center_source != "hips":
        warnings.append(f"center_from_{center_source}")
    if rotation_source != "torso":
        warnings.append(f"rotation_from_{rotation_source}")
    if scale_source != "torso_edges":
        warnings.append(f"scale_from_{scale_source}")

    normalized[valid, :2] = aligned_xy[valid] / scale
    normalized[valid, 2] = raw[valid, 2]
    return normalized, center.astype(np.float32), float(scale), valid_count, warnings


def valid_joint_mask(raw: np.ndarray, min_confidence: float) -> np.ndarray:
    nonzero_xy = np.logical_or(raw[:, 0] != 0.0, raw[:, 1] != 0.0)
    confident = raw[:, 2] > min_confidence
    return np.logical_and(nonzero_xy, confident)


def estimate_center(
    raw: np.ndarray,
    valid: np.ndarray,
) -> tuple[np.ndarray, str]:
    for source, joint_indices in (
        ("hips", (8, 9, 12)),
        ("upper_torso", (1, 2, 5)),
    ):
        selected = [index for index in joint_indices if valid[index]]
        if selected:
            return raw[selected, :2].mean(axis=0), source
    return raw[valid, :2].mean(axis=0), "visible_mean"


def align_body25(
    raw: np.ndarray,
    valid: np.ndarray,
    center: np.ndarray,
    center_source: str,
) -> tuple[np.ndarray, str]:
    shifted = raw[:, :2] - center

    if center_source == "hips" and valid[1]:
        upward = raw[1, :2] - center
        axis_length = float(np.linalg.norm(upward))
        if axis_length > 1e-6:
            upward /= axis_length
            horizontal = np.asarray([-upward[1], upward[0]], dtype=np.float32)
            downward = -upward
            return np.column_stack((shifted @ horizontal, shifted @ downward)), "torso"

    if valid[2] and valid[5]:
        horizontal = raw[5, :2] - raw[2, :2]
        axis_length = float(np.linalg.norm(horizontal))
        if axis_length > 1e-6:
            horizontal /= axis_length
            downward = np.asarray([-horizontal[1], horizontal[0]], dtype=np.float32)
            return np.column_stack((shifted @ horizontal, shifted @ downward)), "shoulders"

    return shifted, "image_axes"


def estimate_scale(raw: np.ndarray, valid: np.ndarray) -> tuple[float, str]:
    edge_lengths = [
        float(np.linalg.norm(raw[first, :2] - raw[second, :2]))
        for first, second in SSG_SCALE_EDGES
        if valid[first]
        and valid[second]
        and np.linalg.norm(raw[first, :2] - raw[second, :2]) > 1e-6
    ]
    if edge_lengths:
        return float(np.median(np.asarray(edge_lengths))), "torso_edges"

    points = raw[valid, :2]
    width_height = points.max(axis=0) - points.min(axis=0)
    bbox_scale = float(np.max(width_height))
    if bbox_scale > 1e-6:
        return bbox_scale, "bbox"

    return 1.0, "unit"


def atomic_save_npy(path: Path, array: np.ndarray, overwrite: bool) -> None:
    prepare_destination(path, overwrite)
    tmp_path = path.with_name(f".{path.name}.tmp")
    with tmp_path.open("wb") as file:
        np.save(file, array)
    tmp_path.replace(path)


def write_pickle(path: Path, payload: Any, overwrite: bool) -> None:
    prepare_destination(path, overwrite)
    tmp_path = path.with_name(f".{path.name}.tmp")
    with tmp_path.open("wb") as file:
        pickle.dump(payload, file, protocol=pickle.HIGHEST_PROTOCOL)
    tmp_path.replace(path)


def write_json(path: Path, payload: Any, overwrite: bool) -> None:
    prepare_destination(path, overwrite)
    tmp_path = path.with_name(f".{path.name}.tmp")
    with tmp_path.open("w", encoding="utf-8") as file:
        json.dump(payload, file, indent=2, sort_keys=True)
        file.write("\n")
    tmp_path.replace(path)


def write_jsonl(path: Path, rows: Iterable[dict[str, Any]], overwrite: bool) -> None:
    prepare_destination(path, overwrite)
    tmp_path = path.with_name(f".{path.name}.tmp")
    with tmp_path.open("w", encoding="utf-8") as file:
        for row in rows:
            json.dump(row, file, sort_keys=True)
            file.write("\n")
    tmp_path.replace(path)


def write_text(path: Path, payload: str, overwrite: bool) -> None:
    prepare_destination(path, overwrite)
    tmp_path = path.with_name(f".{path.name}.tmp")
    with tmp_path.open("w", encoding="utf-8") as file:
        file.write(payload)
    tmp_path.replace(path)


def prepare_destination(path: Path, overwrite: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if (path.exists() or path.is_symlink()) and not overwrite:
        raise FileExistsError(f"Refusing to overwrite existing file: {path}")


def require_dir(path: Path) -> None:
    if not path.is_dir():
        raise FileNotFoundError(f"Required directory not found: {path}")


def require_file(path: Path) -> None:
    if not path.is_file():
        raise FileNotFoundError(f"Required file not found: {path}")


def relative_to(path: Path, root: Path) -> str:
    return str(path.absolute().relative_to(root.absolute()))


def count_labels(labels: Sequence[int]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for label in labels:
        key = str(int(label))
        counts[key] = counts.get(key, 0) + 1
    return dict(sorted(counts.items(), key=lambda item: int(item[0])))


def count_warning_types(
    records: Sequence[DsgSampleRecord | SsgSampleRecord],
) -> dict[str, int]:
    counts: dict[str, int] = {}
    for record in records:
        for warning in record.warnings:
            counts[warning] = counts.get(warning, 0) + 1
    return dict(sorted(counts.items()))


