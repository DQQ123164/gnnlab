#!/usr/bin/env python3
"""Build stable training artifacts for the GNNLab skeleton datasets."""

from __future__ import annotations

import argparse
import logging
from pathlib import Path
from typing import Sequence

if __package__:
    from .preprocessing import (
        DatasetName,
        LOGGER,
        clean_processed_datasets,
        preprocess_dsg,
        preprocess_ssg,
    )
else:
    from preprocessing import (
        DatasetName,
        LOGGER,
        clean_processed_datasets,
        preprocess_dsg,
        preprocess_ssg,
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Preprocess dsg and ssg into reusable gnnlab artifacts.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="Repository root containing dsg/ and ssg/.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Processed output directory. Defaults to ROOT/processed.",
    )
    parser.add_argument(
        "--dsg-source",
        type=Path,
        default=None,
        help=(
            "Directory containing all DSG .skeleton files. Defaults to ROOT/dsg; "
            "ROOT/dsg/nturgb+d_skeletons is also detected."
        ),
    )
    parser.add_argument(
        "--datasets",
        nargs="+",
        choices=("dsg", "ssg", "all"),
        default=["all"],
        help="Dataset groups to process.",
    )
    output_mode = parser.add_mutually_exclusive_group()
    output_mode.add_argument(
        "--overwrite",
        action="store_true",
        help="Replace files previously generated by this script.",
    )
    output_mode.add_argument(
        "--clean",
        action="store_true",
        help="Delete generated output for the selected datasets and exit.",
    )
    parser.add_argument(
        "--ssg-min-confidence",
        type=float,
        default=0.0,
        help="Minimum OpenPose confidence for a joint to affect normalization.",
    )
    parser.add_argument(
        "--log-level",
        default="INFO",
        choices=("DEBUG", "INFO", "WARNING", "ERROR"),
        help="Logging verbosity.",
    )
    parser.add_argument(
        "--no-progress",
        action="store_true",
        help="Disable progress bars and periodic progress messages.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    logging.basicConfig(
        level=getattr(logging, args.log_level),
        format="%(levelname)s %(message)s",
    )

    root = args.root.resolve()
    output_dir = (args.output_dir or root / "processed").resolve()
    selected = expand_datasets(args.datasets)

    if not root.exists():
        raise FileNotFoundError(f"Repository root does not exist: {root}")

    if args.clean:
        clean_processed_datasets(output_dir, selected)
        return

    output_dir.mkdir(parents=True, exist_ok=True)

    if "dsg" in selected:
        preprocess_dsg(
            source_dir=(args.dsg_source or root / "dsg").resolve(),
            output_dir=output_dir / "dsg",
            overwrite=args.overwrite,
            show_progress=not args.no_progress,
        )

    if "ssg" in selected:
        preprocess_ssg(
            source_dir=root / "ssg",
            output_dir=output_dir / "ssg",
            overwrite=args.overwrite,
            min_confidence=args.ssg_min_confidence,
        )

    LOGGER.info("Done. Processed artifacts are under %s", output_dir)


def expand_datasets(values: Sequence[str]) -> set[DatasetName]:
    if "all" in values:
        return {"dsg", "ssg"}
    return {value for value in values if value in {"dsg", "ssg"}}  # type: ignore[return-value]


if __name__ == "__main__":
    main()
